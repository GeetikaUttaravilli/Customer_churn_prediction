CREATE DATABASE CHURN_DB;
CREATE SCHEMA CHURN_DB.CUSTOMER_DATA;
CREATE WAREHOUSE CHURN_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
    USE DATABASE CHURN_DB;

USE SCHEMA CUSTOMER_DATA;
USE WAREHOUSE CHURN_WH;

USE DATABASE CHURN_DB;

USE SCHEMA CUSTOMER_DATA;
CREATE OR REPLACE TABLE CHURN_DB.CUSTOMER_DATA.CHURN_CLEAN AS
SELECT
    CUSTOMERID,
    LOWER(TRIM(GENDER)) AS GENDER,
    TRY_TO_NUMBER(SENIORCITIZEN) AS SENIORCITIZEN,
    LOWER(TRIM(PARTNER)) AS PARTNER,
    LOWER(TRIM(DEPENDENTS)) AS DEPENDENTS,
    TRY_TO_NUMBER(TENURE) AS TENURE,
    LOWER(TRIM(PHONESERVICE)) AS PHONESERVICE,
    LOWER(TRIM(MULTIPLELINES)) AS MULTIPLELINES,
    LOWER(TRIM(INTERNETSERVICE)) AS INTERNETSERVICE,
    LOWER(TRIM(ONLINESECURITY)) AS ONLINESECURITY,
    LOWER(TRIM(ONLINEBACKUP)) AS ONLINEBACKUP,
    LOWER(TRIM(DEVICEPROTECTION)) AS DEVICEPROTECTION,
    LOWER(TRIM(TECHSUPPORT)) AS TECHSUPPORT,
    LOWER(TRIM(STREAMINGTV)) AS STREAMINGTV,
    LOWER(TRIM(STREAMINGMOVIES)) AS STREAMINGMOVIES,
    LOWER(TRIM(CONTRACT)) AS CONTRACT,
    LOWER(TRIM(PAPERLESSBILLING)) AS PAPERLESSBILLING,
    LOWER(TRIM(PAYMENTMETHOD)) AS PAYMENTMETHOD,
    MONTHLYCHARGES AS MONTHLYCHARGES,
    TOTALCHARGES AS TOTALCHARGES,
    CASE
        WHEN CHURN = TRUE THEN 1
        WHEN CHURN = FALSE THEN 0
        ELSE NULL
    END AS CHURN
FROM CHURN_DB.CUSTOMER_DATA.CHURN_RAW
WHERE
    CUSTOMERID IS NOT NULL
    AND TRY_TO_NUMBER(TENURE) IS NOT NULL
    AND MONTHLYCHARGES IS NOT NULL
    AND CHURN IS NOT NULL;
    SELECT COUNT(*) AS CLEANED_CUSTOMERS
FROM CHURN_DB.CUSTOMER_DATA.CHURN_CLEAN;
SELECT
    CHURN,
    COUNT(*) AS CUSTOMER_COUNT
FROM CHURN_DB.CUSTOMER_DATA.CHURN_CLEAN
GROUP BY CHURN
ORDER BY CHURN;
SELECT COUNT(*) AS TOTAL_ROWS
FROM CHURN_DB.CUSTOMER_DATA.CHURN_CLEAN;
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(CUSTOMERID IS NOT NULL) AS CUSTOMERID_PRESENT,
    COUNT_IF(TRY_TO_NUMBER(TENURE) IS NOT NULL) AS TENURE_VALID,
    COUNT_IF(MONTHLYCHARGES IS NOT NULL) AS MONTHLYCHARGES_PRESENT
FROM CHURN_DB.CUSTOMER_DATA.CHURN_RAW;
SELECT
    CHURN,
    COUNT(*) AS CUSTOMER_COUNT
FROM CHURN_DB.CUSTOMER_DATA.CHURN_RAW
GROUP BY CHURN;
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(CHURN = TRUE) AS CHURNED_CUSTOMERS,
    COUNT_IF(CHURN = FALSE) AS RETAINED_CUSTOMERS
FROM CHURN_DB.CUSTOMER_DATA.CHURN_RAW;
SELECT
    CHURN,
    COUNT(*) AS CUSTOMER_COUNT
FROM CHURN_DB.CUSTOMER_DATA.CHURN_CLEAN
GROUP BY CHURN
ORDER BY CHURN;